"""CPU YOLOv8 ONNX adapter returning Clearcam's Nx6 tracking input."""

import ast

import cv2
import numpy as np


class OnnxDetector:
    def __init__(self, config, allowed_classes):
        import onnxruntime as ort

        self.config = config
        self.labels = config["labels"]
        self.class_ids = {self.labels.index(name) for name in allowed_classes}
        options = ort.SessionOptions()
        options.intra_op_num_threads = config["threads"]
        options.inter_op_num_threads = 1
        options.execution_mode = ort.ExecutionMode.ORT_SEQUENTIAL
        self.session = ort.InferenceSession(config["path"], sess_options=options,
                                            providers=["CPUExecutionProvider"])
        inputs = self.session.get_inputs()
        outputs = self.session.get_outputs()
        if len(inputs) != 1 or len(outputs) != 1 or inputs[0].type != "tensor(float)":
            raise ValueError("use a single-input, single-output FP32 YOLOv8 detection export")
        self.input_name = inputs[0].name
        expected = [1, 3, config["input_size"], config["input_size"]]
        if len(inputs[0].shape) != 4 or any(isinstance(x, int) and x != y
                                         for x, y in zip(inputs[0].shape, expected)):
            raise ValueError(f"model input must be NCHW {expected}, including its export image size")
        metadata = self.session.get_modelmeta().custom_metadata_map
        if "names" in metadata:
            names = ast.literal_eval(metadata["names"])
            if isinstance(names, dict):
                names = [names[index] for index in range(len(names))]
            if list(names) != self.labels:
                raise ValueError("model.labels differs from the ONNX model's names metadata")

    def detect(self, frame):
        height, width = frame.shape[:2]
        size = self.config["input_size"]
        scale = min(size / width, size / height)
        resized_width, resized_height = round(width * scale), round(height * scale)
        left, top = (size - resized_width) // 2, (size - resized_height) // 2
        image = np.full((size, size, 3), 114, dtype=np.uint8)
        image[top:top + resized_height, left:left + resized_width] = cv2.resize(
            frame, (resized_width, resized_height))
        tensor = np.ascontiguousarray(image[:, :, ::-1].transpose(2, 0, 1)[None], dtype=np.float32) / 255
        output = self.session.run(None, {self.input_name: tensor})[0]
        return self.decode(output, scale, left, top, width, height)

    def decode(self, output, scale, left, top, width, height):
        channels = 4 + len(self.labels)
        if output.ndim != 3 or output.shape[0] != 1:
            raise ValueError("expected YOLOv8 raw output [1, 4 + class_count, anchors], export nms=False")
        predictions = output[0]
        if predictions.shape[0] == channels:
            predictions = predictions.T
        elif predictions.shape[1] != channels:
            raise ValueError("ONNX output class count differs from model.labels, export nms=False")
        predictions = predictions[np.isfinite(predictions).all(axis=1)]
        predictions = predictions[(predictions[:, 2] > 0) & (predictions[:, 3] > 0)]
        class_ids = predictions[:, 4:].argmax(axis=1)
        scores = predictions[:, 4:].max(axis=1)
        mask = (scores >= self.config["confidence"]) & np.isin(class_ids, list(self.class_ids))
        predictions, class_ids, scores = predictions[mask], class_ids[mask], scores[mask]
        # Keep NMS work and tracker memory bounded even for noisy model outputs.
        order = np.argsort(scores)[::-1][:1000]
        predictions, class_ids, scores = predictions[order], class_ids[order], scores[order]
        boxes = predictions[:, :4].copy()
        boxes[:, :2] -= boxes[:, 2:] / 2
        boxes[:, [0, 2]] /= scale
        boxes[:, [1, 3]] /= scale
        boxes[:, 0] -= left / scale
        boxes[:, 1] -= top / scale
        result = []
        for class_id in np.unique(class_ids):
            indices = np.flatnonzero(class_ids == class_id)
            keep = cv2.dnn.NMSBoxes(boxes[indices].tolist(), scores[indices].tolist(),
                                    self.config["confidence"], self.config["iou_threshold"])
            for index in np.asarray(keep).reshape(-1):
                source = indices[index]
                x, y, w, h = boxes[source]
                x1, y1 = np.clip([x, y], [0, 0], [width, height])
                x2, y2 = np.clip([x + w, y + h], [0, 0], [width, height])
                if x2 > x1 and y2 > y1:
                    result.append([x1, y1, x2, y2, scores[source], class_id])
        result.sort(key=lambda row: row[4], reverse=True)
        return np.asarray(result[:100], dtype=np.float32).reshape(-1, 6)


class DemoDetector:
    """Find the green marker generated by fake_cameras, for pipeline tests only."""

    def __init__(self, labels, allowed_classes):
        if "demo-pest" not in labels or "demo-pest" not in allowed_classes:
            raise ValueError("the demo backend requires the demo-pest label and alert class")
        self.class_id = labels.index("demo-pest")

    def detect(self, frame):
        mask = cv2.inRange(frame, (0, 180, 0), (100, 255, 100))
        contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        detections = []
        for contour in contours:
            x, y, w, h = cv2.boundingRect(contour)
            if w * h >= 100:
                detections.append([x, y, x + w, y + h, 0.99, self.class_id])
        return np.asarray(detections, dtype=np.float32).reshape(-1, 6)
